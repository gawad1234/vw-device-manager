// Generates a computer's install kit scripts: Install.ps1 (self-elevates, runs
// each installer silently in order, logs to install-log.txt, prints a summary)
// and Install.bat (double-click launcher). Pure, with no imports, so Node's test
// runner can load it directly.

export interface KitItem {
  name: string
  /** file name inside the kit's installers\ folder */
  file: string
  args: string
}

/** PowerShell single-quoted literal (quotes doubled; $ and ` stay literal). */
function psStr(s: string): string {
  return "'" + String(s ?? '').replace(/'/g, "''") + "'"
}

/** Kit file names for the given installer paths; same-named files get a numeric prefix. */
export function kitFileNames(paths: string[]): string[] {
  const used = new Set<string>()
  return paths.map((p) => {
    const base = p.split(/[\\/]/).pop() || 'installer'
    let name = base
    for (let n = 2; used.has(name.toLowerCase()); n++) name = `${n}-${base}`
    used.add(name.toLowerCase())
    return name
  })
}

export function generateInstallScript(computer: string, items: KitItem[]): string {
  const entries = items
    .map(
      (it) =>
        `    @{ Name = ${psStr(it.name)}; File = ${psStr(it.file)}; Msi = $${/\.msi$/i.test(it.file)}; Args = ${psStr(it.args)} }`
    )
    .join(',\n')
  return `# Generated by Device Manager - silent software setup for ${computer.replace(/[\r\n]/g, ' ')}
# Double-click Install.bat (or run this file); it asks for admin rights once.

# --- Relaunch elevated if we're not admin ---
$principal = New-Object Security.Principal.WindowsPrincipal(
    [Security.Principal.WindowsIdentity]::GetCurrent())
if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    Start-Process powershell.exe -Verb RunAs -ArgumentList (
        '-ExecutionPolicy', 'Bypass', '-NoProfile', '-File', "\`"$PSCommandPath\`"")
    return
}

$here = Split-Path -Parent $PSCommandPath
Start-Transcript -Path (Join-Path $here 'install-log.txt') -Append | Out-Null
$computer = ${psStr(computer)}
$items = @(
${entries}
)
Write-Host "Setting up $computer - $($items.Count) installer(s)" -ForegroundColor Cyan

$results = @()
$i = 0
foreach ($it in $items) {
    $i++
    $path = Join-Path $here (Join-Path 'installers' $it.File)
    Write-Host "[$i/$($items.Count)] $($it.Name)..." -ForegroundColor Cyan
    if (-not (Test-Path -LiteralPath $path)) {
        $result = 'MISSING (file not in installers folder)'
    } else {
        try {
            if ($it.Msi) {
                $p = Start-Process msiexec.exe -ArgumentList ("/i \`"$path\`" " + $it.Args) -Wait -PassThru
            } else {
                $run = @{ FilePath = $path; Wait = $true; PassThru = $true }
                if ($it.Args) { $run.ArgumentList = $it.Args }
                $p = Start-Process @run
            }
            $result = switch ($p.ExitCode) {
                0 { 'OK' }
                3010 { 'OK (restart needed)' }
                1641 { 'OK (restart started)' }
                default { "FAILED (exit code $($p.ExitCode))" }
            }
        } catch {
            $result = "FAILED ($($_.Exception.Message))"
        }
    }
    $color = if ($result -like 'OK*') { 'Green' } else { 'Red' }
    Write-Host "    $result" -ForegroundColor $color
    $results += [pscustomobject]@{ Software = $it.Name; Result = $result }
}

Write-Host ''
$results | Format-Table -AutoSize | Out-String | Write-Host
if ($results | Where-Object { $_.Result -like '*restart*' }) {
    Write-Host 'Some installers need a restart to finish.' -ForegroundColor Yellow
}
Stop-Transcript | Out-Null
Read-Host 'Done - press Enter to close'
`
}

/** Double-click launcher next to Install.ps1 (bypasses the script execution policy). */
export const INSTALL_BAT =
  '@echo off\r\npowershell.exe -NoProfile -ExecutionPolicy Bypass -File "%~dp0Install.ps1"\r\n'
